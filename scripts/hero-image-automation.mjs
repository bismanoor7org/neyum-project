/**
 * Hero Image Automation — premium Fiji island stills (Unsplash, Fiji-verified IDs).
 * Downloads 2880px cinematic JPEGs for home hero rotation.
 *
 * Usage: node scripts/hero-image-automation.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, "..");
const OUT_DIR = path.join(ROOT, "public", "assets", "hero-images");
const GENERATED_TS = path.join(ROOT, "src", "lib", "hero-images.generated.ts");

/** Premium Fiji hero — fiji-00 is a custom NEYUM asset (not re-downloaded) */
