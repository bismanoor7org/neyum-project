function heroUrl(unsplashId, crop = "entropy") {
  return `https://images.unsplash.com/photo-${unsplashId}?w=2880&h=1620&fit=crop&crop=${crop}&q=95&auto=format&fm=jpg`;
}

async function downloadBuffer(url) {
  const r = await fetch(url, {
    headers: { Accept: "image/jpeg,image/*" },
  });
  if (!r.ok) throw new Error(`Download failed ${r.status}: ${url}`);
  return Buffer.from(await r.arrayBuffer());
}

function writeGeneratedTs(manifest) {
  const entries = manifest.images
    .map(
      (img) => `  {
    title: ${JSON.stringify(img.title)},
    src: ${JSON.stringify(img.src)},
    alt: ${JSON.stringify(img.alt)},
    theme: ${JSON.stringify(img.theme)},
    island: ${JSON.stringify(img.island)},${img.objectPosition ? `\n    objectPosition: ${JSON.stringify(img.objectPosition)},` : ""}
  }`,
    )
    .join(",\n");

  const content = `/** AUTO-GENERATED by scripts/hero-image-automation.mjs — do not edit manually */

export const HERO_IMAGE_MANIFEST_META = {
  version: ${manifest.version},
  generatedAt: ${JSON.stringify(manifest.generatedAt)},
  outputDir: "/assets/hero-images",
  optimization: ${JSON.stringify(manifest.optimization)},
} as const;

export const HOME_HERO_IMAGES_GENERATED = [
${entries}
] as const;
`;
  fs.writeFileSync(GENERATED_TS, content, "utf8");
}

async function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const images = [];

  for (const slide of SLIDES) {
    const dest = path.join(OUT_DIR, `${slide.id}.jpg`);
    const src = `/assets/hero-images/${slide.id}.jpg`;

    if (slide.custom) {
      process.stdout.write(`✓ ${slide.id} (custom, kept) … `);
      const buf = fs.existsSync(dest) ? fs.readFileSync(dest) : Buffer.alloc(0);
      images.push({
        id: slide.id,
        file: `${slide.id}.jpg`,
        src,
        title: slide.title,
        theme: slide.theme,
        island: slide.island,
        alt: `${slide.title} — ${slide.theme}`,
        custom: true,
        objectPosition: slide.objectPosition,
        bytes: buf.length,
        source: "neyum-custom-hero",
      });
      console.log(buf.length ? `${(buf.length / 1024).toFixed(0)} KB` : "missing");
      continue;
    }

    const url = heroUrl(slide.unsplashId, slide.crop ?? "entropy");
    process.stdout.write(`↓ ${slide.id} … `);
    const buf = await downloadBuffer(url);
    fs.writeFileSync(dest, buf);
    images.push({
      id: slide.id,
      file: `${slide.id}.jpg`,
      src,
      title: slide.title,
      theme: slide.theme,
      island: slide.island,
      alt: `${slide.title} — ${slide.theme}`,
      unsplashId: slide.unsplashId,
      objectPosition: slide.objectPosition,
      bytes: buf.length,
      source: url,
    });
    console.log(`${(buf.length / 1024).toFixed(0)} KB`);
  }

  const manifest = {
    version: 2,
    generatedAt: new Date().toISOString(),
    license: "Unsplash License (free commercial use)",
    optimization: {
      width: 2880,
      height: 1620,
      aspect: "16:9",
      quality: 95,
      format: "jpeg",
      fit: "crop",
    },
    images,
  };

  fs.writeFileSync(path.join(OUT_DIR, "manifest.json"), JSON.stringify(manifest, null, 2), "utf8");
  writeGeneratedTs(manifest);
  console.log(`\nDone — ${images.length} hero images → ${OUT_DIR}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
